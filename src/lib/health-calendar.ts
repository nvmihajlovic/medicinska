export function belgradeDate(date: Date) {
  const parts = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Europe/Belgrade", year: "numeric", month: "2-digit", day: "2-digit",
  }).formatToParts(date);
  const value = (type: Intl.DateTimeFormatPartTypes) => {
    const part = parts.find((item) => item.type === type);
    if (!part) throw new Error(`Недостаје део датума: ${type}`);
    return part.value;
  };
  return `${value("year")}-${value("month")}-${value("day")}`;
}

export function healthObservances(date: string) {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(date);
  if (!match) throw new Error("Неисправан датум здравственог календара.");
  const [, year, month, day] = match;
  const parsed = new Date(`${date}T00:00:00Z`);
  if (Number.isNaN(parsed.getTime()) || parsed.toISOString().slice(0, 10) !== date || !monthly[month]) {
    throw new Error("Неисправан датум здравственог календара.");
  }
  const monthDay = `${month}-${day}`;
  const monthTopics = monthly[month];
  return {
    date,
    day: String(Number(day)),
    month: months[Number(month) - 1],
    year,
    daily: (daily[monthDay] ?? []).slice(0, 1),
    weekly: weeks.filter((week) => (!week.year || week.year === year) && monthDay >= week.start && monthDay <= week.end).slice(0, 1),
    monthly: Array.isArray(monthTopics) ? monthTopics.slice(0, 1) : [monthTopics],
  };
}
